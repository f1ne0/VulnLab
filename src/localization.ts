export function localizeVulnerability(vulnerability: Vulnerability, locale: Locale): Vulnerability {
  if (locale !== 'ru') {
    return vulnerability
  }

  const localized = ruVulnerabilityContent[vulnerability.id]
  if (!localized) {
    return vulnerability
  }

  return {
    ...vulnerability,
    name: localized.name,
    shortDescription: localized.shortDescription,
    overview: localized.overview,
    attackMechanism: localized.attackMechanism,
    attackerMindset: localized.attackerMindset,
    defenderMindset: localized.defenderMindset,
    timeToFix: localized.timeToFix,
    attackSteps: localized.attackSteps
  }
}

