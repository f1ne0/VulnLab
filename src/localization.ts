export function localizeOwaspItem<T extends { id: string; title: string; description: string; prevalence: string; detectionDifficulty: string; industries: string[] }>(
  item: T,
  year: '2017' | '2021',
  locale: Locale
): T {
  if (locale !== 'ru') {
    return item
  }

  const localized = ruOwaspContent[`${year}:${item.id}`]
  if (!localized) {
    return item
  }

  return {
    ...item,
    title: localized.title,
    description: localized.description,
    prevalence: localized.prevalence,
    detectionDifficulty: localized.detectionDifficulty,
    industries: localized.industries
  }
}
